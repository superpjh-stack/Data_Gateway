CREATE TABLE IF NOT EXISTS EQP_RUN_LOG (
  RUN_LOG_ID INTEGER PRIMARY KEY,
  EQUIP_ID BIGINT NOT NULL,
  RUN_STATUS VARCHAR(20) NOT NULL,             -- 가동 / 비가동
  STOP_CODE VARCHAR(30),
  START_DT TIMESTAMP NOT NULL,
  END_DT TIMESTAMP,
  STOP_MINUTES NUMERIC(10,2),
  INPUT_TYPE VARCHAR(20) NOT NULL,
  USER_ID BIGINT,
  CREATED_DT TIMESTAMP NOT NULL,
  UPDATED_DT TIMESTAMP
);

-- 트윈 전용 통합 알람 (D-006)
CREATE TABLE IF NOT EXISTS TWIN_ALARM (
  ALARM_ID INTEGER PRIMARY KEY,
  CATEGORY VARCHAR(10) NOT NULL,               -- CCP / COMM
  RULE_ID VARCHAR(30) NOT NULL,
  ITEM VARCHAR(50) NOT NULL,
  EQUIP_CODE VARCHAR(30) NOT NULL,
  SEVERITY VARCHAR(10) NOT NULL,
  MESSAGE VARCHAR(300) NOT NULL,
  VALUE VARCHAR(50),
  VALUE_KEY VARCHAR(30),                       -- 조건 구분(절임통 번호, 통신 대상)
  STATE VARCHAR(10) NOT NULL,                  -- RAISED / ACKED / CLEARED
  RAISED_DT TIMESTAMP NOT NULL,
  ACKED_DT TIMESTAMP,
  CLEARED_DT TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IX_ALARM_STATE ON TWIN_ALARM(STATE);

-- 트윈 전용 일일 정리 이력 (D-017)
CREATE TABLE IF NOT EXISTS TWIN_PURGE_LOG (
  PURGE_ID INTEGER PRIMARY KEY,
  TRIGGER_TYPE VARCHAR(10) NOT NULL,           -- SCHEDULE / MANUAL
  STARTED_DT TIMESTAMP NOT NULL,
  CUTOFF_DT TIMESTAMP NOT NULL,                -- 이 시각 이전 수집분 삭제
  DELETED_JSON TEXT NOT NULL,                  -- 테이블별 삭제 행 수
  DELETED_TOTAL INTEGER NOT NULL,
  DB_BYTES_BEFORE INTEGER,
  DB_BYTES_AFTER INTEGER,
  ELAPSED_MS INTEGER NOT NULL
);
