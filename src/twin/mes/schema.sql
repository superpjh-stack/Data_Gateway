);

CREATE TABLE IF NOT EXISTS PKG_WEIGHT_INSP (
  WEIGHT_INSP_ID INTEGER PRIMARY KEY,
  WORK_ORDER_ID BIGINT NOT NULL,
  ITEM_ID BIGINT NOT NULL,
  STD_WEIGHT NUMERIC(10,3) NOT NULL,
  MEASURE_WEIGHT NUMERIC(10,3) NOT NULL,
  GAP_WEIGHT NUMERIC(10,3),
